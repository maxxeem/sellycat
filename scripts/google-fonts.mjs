/**
 * Regenerates src/lib/design/google-fonts.ts from Google's public font catalog: every family that
 * covers Latin (so German/English shop texts render), most popular first, with its category.
 * Run: node scripts/google-fonts.mjs
 */
import { writeFileSync } from "node:fs";

const CAT = { "Sans Serif": "s", Serif: "r", Display: "d", Handwriting: "h", Monospace: "m" };
const res = await fetch("https://fonts.google.com/metadata/fonts");
if (!res.ok) throw new Error(`catalog ${res.status}`);
const data = JSON.parse((await res.text()).replace(/^\)\]\}'/, ""));
const list = data.familyMetadataList
  .filter((f) => f.subsets.includes("latin") && CAT[f.category] && !f.colorCapabilities?.length)
  .sort((a, b) => a.popularity - b.popularity)
  .map((f) => `${f.family}|${CAT[f.category]}`);

const out = `// Generated by scripts/google-fonts.mjs from Google's font catalog. Do not edit by hand.
/** Every Google Font with Latin support (served through our proxy, never from Google directly), most popular first. */
export type FontCategory = "s" | "r" | "d" | "h" | "m";

const RAW = ${JSON.stringify(list.join("\n"))};

export const GOOGLE_FONT_LIST: ReadonlyArray<{ family: string; category: FontCategory }> = RAW.split("\\n").map((line) => {
  const [family, category] = line.split("|");
  return { family: family!, category: category as FontCategory };
});

/** Family names only (same order). */
export const GOOGLE_FONTS: readonly string[] = GOOGLE_FONT_LIST.map((f) => f.family);

const NAMES = new Set(GOOGLE_FONTS);
export const isGoogleFont = (family: string) => NAMES.has(family);
`;
writeFileSync(new URL("../src/lib/design/google-fonts.ts", import.meta.url), out);
console.log(`${list.length} fonts`);
